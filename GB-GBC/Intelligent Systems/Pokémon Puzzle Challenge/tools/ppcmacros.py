NOTE_NAMES = ['C_', 'Cs', 'D_', 'Ds', 'E_', 'F_', 'Fs', 'G_', 'Gs', 'A_', 'As', 'B_']


def _consts():
    out = ['; ---- music track bytes ----',
           '; $01-$6C  length in ticks for the following events (plain numbers)',
           '; $6D-$89  drum DRM00-DRM28 (index into DrumTable, ch1 from entry 0, ch2-ch4 from entry 7)',
           '; $8A-$D1  note C_2-B_7 (ch4: noise index NZ00-NZ71 into NoiseTable)']
    for n in range(72):
        out.append(f'DEF {NOTE_NAMES[n % 12]}{n // 12 + 2} EQU ${0x8A + n:02X}')
    for n in range(72):
        out.append(f'DEF NZ{n:02} EQU ${0x8A + n:02X}')
    for n in range(29):
        out.append(f'DEF DRM{n:02} EQU ${0x6D + n:02X}')
    out.append('DEF REST EQU $D2  ; release the note (envelope release), wait')
    out.append('DEF HOLD EQU $D3  ; keep the note sounding, wait')
    return '\n'.join(out)



# Generator: Pyramids of Ra (U) bank 2 sound driver + data -> PyramidsOfRa_sound.asm
import sys
import os; sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from emit import *
# usage: gen_ra.py <Pyramids of Ra ROM> [output .asm]
rom=Rom(sys.argv[1])
BK=2
L={0x4000:'RaSnd_PlaySong',0x4068:'RaSongTable',
 0x40A4:'RaSnd_Update',0x40B1:'.tick',0x40C7:'.vibrato',0x40D0:'.done',
 0x40D1:'RaSnd_StopMusic',
 0x40D6:'RaSnd_Ch1Events',0x40D7:'.loop',0x4139:'.next',0x4147:'.done',0x4149:'.progChange',
 0x4150:'RaSnd_Ch1Vibrato',0x4171:'.down',0x417D:'.done',
 0x417E:'RaSnd_LoadCh1Inst',0x4181:'RaSnd_LoadInst',
 0x41AE:'RaSnd_Ch2Events',0x41AF:'.loop',0x4202:'.next',0x4210:'.done',0x4212:'.progChange',
 0x4219:'RaSnd_Ch2Vibrato',0x423A:'.down',0x4246:'.done',
 0x4247:'RaSnd_LoadCh2Inst',
 0x4277:'RaSnd_Ch4Events',0x4278:'.loop',0x42C0:'.done',
 0x42C2:'RaSnd_AdvanceClock',0x42CC:'.checkBar',0x42F1:'.done',
 0x42F2:'RaSnd_CmpBar',0x430C:'RaSnd_CmpTick',0x431D:'.done',
 0x431E:'RaSnd_PlaySfx',0x4354:'.done',0x4355:'RaSnd_SfxTimer',0x4365:'.done'}
RAM={0xC4EF:'wRaPtrCh4',0xC4F0:'wRaPtrCh4+1',0xC4F1:'wRaPtrCh2',0xC4F2:'wRaPtrCh2+1',
 0xC4F3:'wRaPtrCh1',0xC4F4:'wRaPtrCh1+1',0xC4F5:'wRaPtrCh3',0xC4F6:'wRaPtrCh3+1',
 0xC4F9:'wRaInstCh1',0xC4FA:'wRaTransposeCh1',0xC4FB:'wRaCh1NR12',0xC4FC:'wRaCh1NR10',
 0xC4FD:'wRaCh1NR11',0xC4FE:'wRaSfxTimer',0xC4FF:'wRaSfxNote',0xC500:'wRaCh1FreqLo',
 0xC501:'wRaCh1VibPattern',0xC502:'wRaCh1VibStep',0xC503:'wRaCh1VibMask',
 0xC504:'wRaInstCh2',0xC505:'wRaTransposeCh2',0xC506:'wRaCh2NR22',0xC507:'wRaCh2NR10',
 0xC508:'wRaCh2NR21',0xC509:'wRaCh2Note',0xC50A:'wRaCh2Len',0xC50B:'wRaCh2FreqLo',
 0xC50C:'wRaCh2VibPattern',0xC50D:'wRaCh2VibStep',0xC50E:'wRaCh2VibMask',
 0xC50F:'wRaSfxActive',0xC510:'wRaMusicOn',0xC511:'wRaSndEnabled',0xC512:'wRaTickCount',
 0xC513:'wRaClockHi',0xC514:'wRaClockLo',0xC515:'wRaBar',0xC516:'wRaSongBars',
 0xC517:'wRaSong',0xC518:'wRaTicksPerFrame'}
RAMC={0xC4EF:'event pointers (ch4 noise, ch2, ch1, ch3 = loaded but never used)',
 0xC4F9:'always 0: program changes are skipped',0xC4FE:'SFX frames left',
 0xC4FF:'SFX note index (instrument byte 3)',0xC507:'loaded, unused',0xC509:'loaded, unused',
 0xC50A:'loaded, unused',0xC50F:'$FF while an SFX owns ch1',0xC510:'game copies its music option here every frame',
 0xC511:'0 = driver does nothing (game flag)',0xC512:'free-running; masked for the vibrato rate',
 0xC513:'12-bit position in the bar, hi',0xC514:'... lo; wraps at $2FC',0xC515:'bar counter',
 0xC516:'bars in the song; reaching it restarts the song',0xC518:'clock ticks run per frame'}
INSTTAB=0x43DE; NINST=24
insts=[rom.w(BK,INSTTAB+2*i) for i in range(NINST)]
IMM={0x4068:'RaSongTable',0x4366:'RaNoiseLenTable',0x4372:'RaFreqTable',0x43DE:'RaInstTable',
     0x0000:'0',0x0001:'1',0x0003:'3',0x0004:'4',0x0005:'5'}
CM={0x4000:'a = song id',0x40FA:'status $01 on ch1 = stop music (unused in data)',
 0x40FE:'status $74 = park this track (unused in data)',0x4104:'program change: ignored',
 0x412A:'note - transpose; below 0 = skipped',0x429A:'drum notes $48-$53 pick a length',
 0x42A6:'NR42: vol 15, "increase"',0x42AA:'NR43',0x42AE:'trigger + length enable',
 0x42CF:'bar = $2FC ticks (ticks $2FC-$2FF never happen)',0x431E:'a = SFX id = instrument number',
 0x416A:'(stored twice)',0x4233:'(stored twice)'}
out=[]
P=out.append
P('; Pyramids of Ra (U) - sound driver and data, bank $02 $4000-$7FFF')
P('; Generated by tools/gen_ra.py. Assembles byte-identical with RGBDS 1.0.0.')
P('')
P('INCLUDE "hardware.inc"')
P('INCLUDE "ra_sound.inc"')
P('')
P('; ---- WRAM ----')
out+=ram_equs({a:n for a,n in RAM.items() if '+' not in n},RAMC)
P('')
P('SECTION "Pyramids of Ra sound", ROMX[$4000], BANK[$02]')
P('')
out+=code_lines2(rom,BK,0x4000,0x4068,L,RAM,CM,IMM)
# song table
songs=[]
P('')
P('; 12 bytes per song: ch4 events, ch2 events, ch1 events, ch3 (unused),')
P('; ticks per frame, bars, ch1 transpose, ch2 transpose')
P('RaSongTable:')
tracks={}
for i in range(5):
    a=0x4068+12*i; p=[rom.w(BK,a+2*k) for k in range(4)]; e=rom.bytes(BK,a+8,4)
    songs.append((p,e))
for i,(p,e) in enumerate(songs):
    for ch,ptr in zip(('Ch4','Ch2','Ch1'),p[:3]):
        tracks.setdefault(ptr,[]).append('RaSong%d_%s'%(i,ch))
def tname(ptr): return tracks[ptr][0]
for i,(p,e) in enumerate(songs):
    P('\tsong_header %s, %s, %s, %s, %d, %d, %s, %s\t; song %d'%(tname(p[0]),tname(p[1]),tname(p[2]),
       '0' if p[3]==0 else hx(p[3],4),e[0],e[1],hx(e[2]),hx(e[3]),i))
P('')
out+=code_lines2(rom,BK,0x40A4,0x4366,L,RAM,CM,IMM)
P('')
P('; NR41 length for drum notes $48-$53 (ch4 only plays one noise, NR42=$F9 NR43=$17)')
P('RaNoiseLenTable:')
out+=db_lines(rom.bytes(BK,0x4366,12),12)
P('')
P('; Frequency table, indexed by (MIDI note - transpose). Entries 0-5 are 0; 6 = C2 ... 53 = B5.')
P('RaFreqTable:')
fr=[rom.w(BK,0x4372+2*i) for i in range(54)]
for i in range(0,54,8): P('\tdw '+', '.join(hx(x,4) for x in fr[i:i+8]))
P('')
P('; Instrument = SFX table. Music always uses instrument 0 (program changes are')
P('; skipped); RaSnd_PlaySfx(a) plays instrument a on ch1.')
P('RaInstTable:')
for i in range(0,NINST,4): P('\tdw '+', '.join('RaInst%02d'%k for k in range(i,min(i+4,NINST))))
P('')
P('; ra_inst NR12, NR10, NR11, SFX note index, SFX frames, vibrato pattern, vibrato step, vibrato rate mask')
for i in range(NINST):
    assert insts[i]==0x440E+8*i
    b=rom.bytes(BK,insts[i],8)
    P('RaInst%02d:\tra_inst %s'%(i,', '.join(hx(x) for x in b)))
P('')
# tracks
starts=sorted(tracks)+[0x7FF2]
assert starts[0]==0x44CE
NN=['C_','Cs','D_','Ds','E_','F_','Fs','G_','Gs','A_','As','B_']
def mn(n): return '%s%d'%(NN[n%12],n//12-1)
for s,e in zip(starts,starts[1:]):
    for nm in tracks[s][1:]: P('%s:\t; shared'%nm)
    P('%s:'%tracks[s][0])
    if len(tracks[s])>1: P('\t; used by: '+', '.join(tracks[s]))
    a=s
    while a<e:
        b=rom.bytes(BK,a,5)
        bar=(b[0]<<4)|(b[1]>>4); t=((b[1]&15)<<8)|b[2]
        st=b[3]
        if st&0xF0==0x90: P('\tnote_on %d, %s, %d, %s'%(bar,hx(t,3),st&15,mn(b[4])))
        elif st&0xF0==0xC0: P('\tprog_chg %d, %s, %d, %s'%(bar,hx(t,3),st&15,hx(b[4])))
        elif st==0 and b[4]==0 and t==0: P('\ttrack_end %d'%bar)
        else: P('\tevent %d, %s, %s, %s'%(bar,hx(t,3),hx(st),hx(b[4])))
        a+=5
    assert a==e,(hex(s),hex(a),hex(e))
    P('')
P('; $7FF2-$7FFF: filler after the last track (never read)')
P('RaUnused_7FF2:')
out+=db_lines(rom.bytes(BK,0x7FF2,14),14)
open(sys.argv[2] if len(sys.argv)>2 else 'PyramidsOfRa_sound.asm','w').write('\n'.join(out)+'\n')

def gen_dd3(path,outp):
    rom=Rom(path)
    L={0x3B00:'DdSnd_Update',0x3B09:'.voices',
     0x3B6B:'DdSnd_Play',0x3B95:'.rest',0x3B9A:'.lookup',0x3BA9:'.setFreq',0x3BCF:'.ch1',
     0x3C2F:'.ch2',0x3C8D:'.ch4',0x3CAC:'.rawVol',0x3CAF:'.nr43',
     0x3CCE:'DdSnd_Voices',0x3CF4:'.ch1Env',0x3CFF:'.ch1Step',0x3D22:'.ch1Pos',0x3D35:'.ch1Count',
     0x3D40:'.ch1Next',0x3D65:'.ch1Off',0x3D76:'.ch2',0x3D90:'.ch2Env',0x3D9B:'.ch2Step',
     0x3DBE:'.ch2Pos',0x3DD1:'.ch2Count',0x3DDC:'.ch2Next',0x3E01:'.ch2Off',0x3E12:'.ch4',
     0x3E30:'DdSnd_PlaySong',0x3E5C:'DdSnd_Sequencer',0x3E8E:'.ch2',0x3EBF:'.ch4',
     0x3EEF:'DdSnd_LoopSong',0x3EF5:'DdSnd_StopMusic',0x3FA7:'DdSnd_PlaySfx',0x3FBB:'.pulse',
     0x3FDE:'.noise'}
    R={0xC000:'wSndVolume',0xC001:'wSndV1State',0xC002:'wSndV1EnvPtr',0xC003:'wSndV1EnvPtr+1',
     0xC004:'wSndV1EnvDelta',0xC005:'wSndV1EnvCount',0xC006:'wSndV1EnvRate',0xC007:'wSndV1EnvTimer',
     0xC008:'wSndV1FreqLo',0xC009:'wSndV1FreqHi',0xC00A:'wSndV1Dur',
     0xC00B:'wSndV2State',0xC00C:'wSndV2EnvPtr',0xC00D:'wSndV2EnvPtr+1',0xC00E:'wSndV2EnvDelta',
     0xC00F:'wSndV2EnvCount',0xC010:'wSndV2EnvRate',0xC011:'wSndV2EnvTimer',0xC012:'wSndV2FreqLo',
     0xC013:'wSndV2FreqHi',0xC014:'wSndV2Dur',0xC015:'wSndV4State',0xC016:'wSndV4Dur',
     0xC017:'wSndPan',0xC018:'wSndFreqLo',0xC019:'wSndFreqHi',0xC01A:'wSndDuration',
     0xC01B:'wSndGate1',0xC01C:'wSndGate2',0xC01D:'wSndGate4',0xC01E:'wSndTempo',
     0xC01F:'wMusPtr1',0xC020:'wMusPtr1+1',0xC021:'wMusPtr2',0xC022:'wMusPtr2+1',
     0xC023:'wMusPtr4',0xC024:'wMusPtr4+1',0xC025:'wMusSong',0xC026:'wMusPlaying'}
    RC={0xC000:'high nibble OR-added to every NRx2 low nibble; game sets $F0',
     0xC001:'voice 1 (ch1): 0 = sounding, $FF = idle',0xC00B:'voice 2 (ch2)',
     0xC015:'voice 4 (ch4): $80 sounding, $FF idle',0xC017:'Play: NR51 bits (c)',
     0xC01A:'Play: length code 1-6, scaled to frames by DdDurTable',
     0xC01B:'last note byte per sequencer channel; 0 = rest',0xC01D:'stored, never read',
     0xC01E:'DdDurTable row; game sets 4',0xC01F:'sequencer pointers',0xC025:'$FF = none',
     0xC026:'DdSnd_Update runs the sequencer while nonzero'}
    IMM={0x3B2A:'DdDurTable',0x3F1A:'DdFreqTable',0x3B0C:'DdInstTable',0x3AD2:'DdSongTable',
         0x3F7A:'DdSfxTable',0x000B:'$000B',0x0311:'$0311',0x0811:'$0811'}
    CM={0x3B6B:'a = note index, b = instrument, c = NR51 bits, [wSndDuration] = length code',
        0x3B89:'ch4 rest ($00 - $48)',0x3B8D:'ch1/ch2 rest ($00 - $24)',0x3B91:'(same test twice)',
        0x3BCC:'"jp z" in v1; here every type >= 4 goes to ch4',
        0x3BE2:'NRx2 = (inst & $0F) + wSndVolume',0x3C9F:'wSndVolume >= $A0: raw inst value',
        0x3C91:'zero frequency (rest) = no hit',
        0x3E88:'b = 0 (ch1 inst), c = $0B: ch1+ch2+ch4 right only',
        0x3EB9:'b = 3 (ch2 inst), c = $11',0x3EE9:'b = 8 (drum inst), c = $11',
        0x3E6B:'$FE: restart song',0x3E70:'$FF: stop',
        0x3FB3:'SFX 0-4 noise, 5-8 ch1',0x3FC7:'BUG: reads ROM $0011 ($CF) instead of ld a,$11'}
    out=HDR('Double Dragon 3 (U) - sound driver (Source engine, version 2) and data','gen_src.py')
    P=out.append
    P('INCLUDE "hardware.inc"'); P('DEF SRC_VER EQU 2'); P('INCLUDE "source_sound.inc"'); P('')
    out+=ram_equs({a:n for a,n in R.items() if '+' not in n},RC); P('')
    P('SECTION "DD3 sound driver", ROM0[$3AD2]'); P('')
    songs=[[rom.w(0,0x3AD2+6*i+2*k) for k in range(3)] for i in range(7)]
    P('; Song = (ch2, ch1, ch4) sequences in bank 7. The game maps bank 7 before')
    P('; calling the driver.')
    P('DdSongTable:')
    for i in range(7): P('\tdw DdSong%d_Ch2, DdSong%d_Ch1, DdSong%d_Ch4\t; %d'%(i,i,i,i))
    P('')
    envn={0x3AFC:'DdEnv_Hold'}
    l,a=env_lines(rom,0,0x3AFC,envn[0x3AFC]); out+=l; assert a==0x3B00
    P('')
    out+=code_lines2(rom,0,0x3B00,0x3B0C,L,R,{0x3B00:'game calls this every frame (bank 7 mapped)'},IMM)
    P('')
    P('DdInstTable:')
    it=[rom.w(0,0x3B0C+2*i) for i in range(9)]
    nm={0x3B1E:'DdInst_Pulse1',0x3B23:'DdInst_Pulse2',0x3B28:'DdInst_Noise'}
    P('\tdw '+', '.join(nm[x] for x in it))
    s,n=inst_lines(rom,0,0x3B1E,envn,{}); P('DdInst_Pulse1:%s'%s)
    s,n=inst_lines(rom,0,0x3B23,envn,{}); P('DdInst_Pulse2:%s'%s)
    P('DdInst_Noise:\t; inst_noise $A1, $21 - its NR43 byte is the first byte of DdDurTable')
    P('\tdb 4, $A1')
    P('')
    P('; Length code (1-6) -> frames, one row of 8 per tempo (wSndTempo). Row r gives')
    P('; 1x 2x 3x 4x 6x 8x of (r+3) frames. The game always uses row 4 (7 frames).')
    P('DdDurTable:')
    for r in range(8): P('\tdb '+', '.join(hx(x) for x in rom.bytes(0,0x3B2A+8*r,8))+'\t; tempo %d'%r)
    P('\tdb $00\t; unused')
    P('')
    out+=code_lines2(rom,0,0x3B6B,0x3F1A,L,R,CM,IMM)
    P(''); P('; 48 notes, C2-B5'); P('DdFreqTable:')
    fr=[rom.w(0,0x3F1A+2*i) for i in range(48)]
    for i in range(0,48,12): P('\tdw '+', '.join(hx(x,4) for x in fr[i:i+12]))
    P('')
    P('; SFX 0-4: noise (NR41, NR42, NR43, NR44, unused); SFX 5-8: ch1 (NR10-NR14)')
    P('DdSfxTable:')
    for i in range(9):
        b=rom.bytes(0,0x3F7A+5*i,5)
        P('\t%s %s\t; %d'%('sfx_noise' if i<5 else 'sfx_pulse',', '.join(hx(x) for x in b),i))
    P('')
    out+=code_lines2(rom,0,0x3FA7,0x4000,L,R,CM,IMM)
    P('')
    P('SECTION "DD3 music", ROMX[$4000], BANK[$07]'); P('')
    P('; Sequences: note NOTE, len / drum byte, len / rest len (len = code 1-6),')
    P('; snd_loop ($FE, restarts the whole song) / snd_end ($FF, stops all music).')
    tl={}
    for i,(c2,c1,c4) in enumerate(songs):
        tl.setdefault(c4,[]).append(('DdSong%d_Ch4'%i,'d',''))
        tl.setdefault(c1,[]).append(('DdSong%d_Ch1'%i,'p',''))
        tl.setdefault(c2,[]).append(('DdSong%d_Ch2'%i,'p',''))
    out+=track_lines(rom,7,0x4000,0x5B59,tl,2,None)
    P('; $5B59-$7FFF: not sound data (unprogrammed/garbage fill)')
    open(outp,'w').write('\n'.join(out)+'\n')
    return [(0,0x3AD2,0x4000),(7,0x4000,0x5B59)]

if __name__=='__main__':
    # usage: gen_src.py <Workboy ROM> <Double Dragon 3 ROM> [output dir]
    O=(sys.argv[3] if len(sys.argv)>3 else '.').rstrip('/\\')+os.sep
    r1=gen_workboy(sys.argv[1],O+'Workboy_sound.asm')
    r2=gen_dd3(sys.argv[2],O+'DoubleDragon3_sound.asm')
    for name,r in (('Workboy',r1),('DD3',r2)):
        print(name,'regions checked:',', '.join('%02X:%04X-%04X'%(b,l,h-1) for b,l,h in r))

# Generator: Source sound driver (Workboy = version 1, Double Dragon 3 = version 2)
import sys
import os; sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from emit import *
NN=['C_','Cs','D_','Ds','E_','F_','Fs','G_','Gs','A_','As','B_']
def nname(idx): return '%s%d'%(NN[idx%12],2+idx//12)

def env_lines(rom,bk,a,label):
    out=['%s:'%label]
    while True:
        b=rom.b(bk,a)
        if b==0x63: out.append('\tenv_end'); return out,a+1
        d,c,r=rom.bytes(bk,a,3)
        out.append('\tenv_step %d, %d, %d'%(d-256 if d>=128 else d,c,r)); a+=3

def track_lines(rom,bk,lo,hi,labels,ver,chkind):
    """walk lo..hi linearly; labels addr->(name,kind). kind: 'p' pitched, 'd' drum."""
    out=[]; a=lo; kind=None
    while a<hi:
        if a in labels:
            for nm,k,cmt in labels[a]:
                out.append('%s:%s'%(nm,('\t; '+cmt) if cmt else '')); kind=k
        b=rom.b(bk,a)
        if b==0xFF:
            if ver==1:
                assert rom.b(bk,a+1)==1
                out.append('\tsnd_end'); a+=2
            else: out.append('\tsnd_end'); a+=1
            out.append('')
            continue
        if ver==2 and b==0xFE: out.append('\tsnd_loop'); out.append(''); a+=1; continue
        if ver==1 and b>=0xF0: out.append('\tsnd_inst %d'%(b&15)); a+=1; continue
        if a+1 in labels:
            idx=b-(0x30 if ver==1 else 0x24)
            out.append('\tdb SRC_NOTE_BASE + %s\t; note %s whose length byte is the next sequence\'s first byte'%(nname(idx),nname(idx)))
            out.append('\t; (no end marker: this channel runs on into the next sequence)')
            a+=1; continue
        dur=rom.b(bk,a+1)
        if b==0: out.append('\trest %d'%dur)
        elif kind=='d': out.append('\tdrum %s, %d'%(hx(b),dur))
        else:
            idx=b-(0x30 if ver==1 else 0x24)
            c='\t; past the end of the frequency table' if idx>=48 else ''
            out.append('\tnote %s, %d%s'%(nname(idx),dur,c))
        a+=2
    assert a==hi,(hex(a),hex(hi))
    return out

def inst_lines(rom,bk,a,envnames,wavenames):
    t=rom.b(bk,a)
    if t in (1,2):
        b=rom.bytes(bk,a,5); e=b[3]|b[4]<<8
        return '\tinst_pulse%d %s, %s, %s'%(t,hx(b[1]),hx(b[2]),envnames[e]),5
    if t==3:
        b=rom.bytes(bk,a,6); e=b[2]|b[3]<<8; w=b[4]|b[5]<<8
        return '\tinst_wave %s, %s, %s'%(hx(b[1]),envnames[e],wavenames[w]),6
    if t==4:
        b=rom.bytes(bk,a,3)
        return '\tinst_noise %s, %s'%(hx(b[1]),hx(b[2])),3
    raise ValueError

HDR=lambda title,gen: [
 '; %s'%title,'; Generated by tools/%s. Assembles byte-identical with RGBDS 1.0.0.'%gen,'']


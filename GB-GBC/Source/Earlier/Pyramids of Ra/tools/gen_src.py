def gen_workboy(path,outp):
    rom=Rom(path)
    L={0x33FC:'WbSnd_Play',0x340B:'.lookup',0x341A:'.setFreq',0x3443:'.ch1',0x349C:'.ch2',
     0x34F3:'.ch3',0x3507:'.waveLoop',0x3556:'.ch4',
     0x357E:'WbSnd_Voices',0x35A4:'.ch1Env',0x35AF:'.ch1Step',0x35D2:'.ch1Pos',0x35E5:'.ch1Count',
     0x35F0:'.ch1Next',0x3615:'.ch1Off',0x3626:'.ch2',0x3640:'.ch2Env',0x364B:'.ch2Step',
     0x366E:'.ch2Pos',0x3681:'.ch2Count',0x368C:'.ch2Next',0x36B1:'.ch2Off',0x36C2:'.ch3',
     0x36CE:'.ch3Step',0x36FA:'.ch3Pos',0x370D:'.ch3Count',0x3718:'.ch3Next',0x373D:'.ch3Off',
     0x374E:'.ch4',0x376C:'WbSnd_PlaySong',0x379C:'WbSnd_Sequencer',0x37AA:'.ch1Read',
     0x37B8:'.ch1Note',0x37D4:'.ch2',0x37E2:'.ch2Read',0x37F0:'.ch2Note',0x380C:'.done',
     0x380D:'WbSnd_StopMusic'}
    R={0xC3B2:'wSndV1State',0xC3B3:'wSndV1EnvPtr',0xC3B4:'wSndV1EnvPtr+1',0xC3B5:'wSndV1EnvDelta',
     0xC3B6:'wSndV1EnvCount',0xC3B7:'wSndV1EnvRate',0xC3B8:'wSndV1EnvTimer',0xC3B9:'wSndV1FreqLo',
     0xC3BA:'wSndV1FreqHi',0xC3BB:'wSndV1Dur',
     0xC3BC:'wSndV2State',0xC3BD:'wSndV2EnvPtr',0xC3BE:'wSndV2EnvPtr+1',0xC3BF:'wSndV2EnvDelta',
     0xC3C0:'wSndV2EnvCount',0xC3C1:'wSndV2EnvRate',0xC3C2:'wSndV2EnvTimer',0xC3C3:'wSndV2FreqLo',
     0xC3C4:'wSndV2FreqHi',0xC3C5:'wSndV2Dur',
     0xC3C6:'wSndV3State',0xC3C7:'wSndV3EnvPtr',0xC3C8:'wSndV3EnvPtr+1',0xC3C9:'wSndV3EnvDelta',
     0xC3CA:'wSndV3EnvCount',0xC3CB:'wSndV3EnvRate',0xC3CC:'wSndV3EnvTimer',0xC3CD:'wSndV3FreqLo',
     0xC3CE:'wSndV3FreqHi',0xC3CF:'wSndV3Dur',0xC3D0:'wSndV4State',0xC3D1:'wSndV4Dur',
     0xC3D2:'wSndPan',0xC3D3:'wSndFreqLo',0xC3D4:'wSndFreqHi',0xC3D5:'wSndDuration',
     0xC3D6:'wSndGate1',0xC3D7:'wSndGate2',0xC3D8:'wMusPtr1',0xC3D9:'wMusPtr1+1',
     0xC3DA:'wMusPtr2',0xC3DB:'wMusPtr2+1',0xC3DC:'wMusInst1',0xC3DD:'wMusInst2',
     0xC3DE:'wMusSong',0xC3DF:'wMusPlaying'}
    RC={0xC3B2:'voice 1 (ch1): 0 = sounding, $FF = idle',0xC3BC:'voice 2 (ch2)',
     0xC3C6:'voice 3 (ch3); its Dur counts envelope steps, not frames',0xC3D0:'voice 4 (ch4): $80 sounding, $FF idle',
     0xC3D2:'Play: NR51 bits for the voice (c)',0xC3D3:'Play: frequency from the note',
     0xC3D5:'Play: length in frames (game sets it before the call)',
     0xC3D6:'last ch1 note byte from the sequencer; 0 (rest) mutes voice 1',0xC3D7:'same for ch2 / voice 2',
     0xC3D8:'sequencer pointers',0xC3DC:'instrument for each sequencer channel (0 and 3)',
     0xC3DE:'$FF = none',0xC3DF:'game calls WbSnd_Sequencer while nonzero'}
    IMM={0x382D:'WbFreqTable',0x33C9:'WbInstTable',0x388D:'WbSongTable',0x1030:'$1030'}
    CM={0x33FC:'a = note index (byte - $30), b = instrument, c = NR51 bits',
        0x3402:'note byte 0 (rest) arrives here as $D0',0x3421:'(NR51 is read-modify-written below)',
        0x3451:'gate: ch1 rest',0x34AA:'gate: ch2 rest',0x3504:'b = 16 bytes, c = $30 (wave RAM)',
        0x37B4:'$F0-$FE: low nibble discarded, byte skipped',0x37BB:'note byte -> index',
        0x37CF:'NR51 bits $11',0x3807:'NR51 bits $11',
        0x358F:'gate closed: mute ch1',0x35F9:'$63 = envelope end, voice off',
        0x3695:'$63 = envelope end',0x3721:'$63 = envelope end'}
    out=HDR('Workboy (U) (Unreleased) - sound driver (Source engine, version 1) and data','gen_src.py')
    P=out.append
    P('INCLUDE "hardware.inc"'); P('DEF SRC_VER EQU 1'); P('INCLUDE "source_sound.inc"'); P('')
    out+=ram_equs({a:n for a,n in R.items() if '+' not in n},RC); P('')
    # envelopes in bank 0 lower half
    envn={0x0B76:'WbEnv_Vibrato',0x0B95:'WbEnv_Short',0x33B1:'WbEnv_Hold',0x33B5:'WbEnv_Blip'}
    wavn={0x33B9:'WbWave_33B9'}
    P('SECTION "Workboy sound envelopes A", ROM0[$0B76]'); P('')
    P('; Pitch envelopes: env_step delta, steps, frames_per_step. Every frames_per_step')
    P('; frames the voice frequency moves by delta; after `steps` steps the next entry')
    P('; loads. env_end ($63) switches the voice off.')
    l,a=env_lines(rom,0,0x0B76,envn[0x0B76]); out+=l; assert a==0x0B95
    l,a=env_lines(rom,0,0x0B95,envn[0x0B95]); out+=l; assert a==0x0B99
    P('')
    P('SECTION "Workboy sound driver", ROM0[$33B1]'); P('')
    l,a=env_lines(rom,0,0x33B1,envn[0x33B1]); out+=l
    l,a=env_lines(rom,0,0x33B5,envn[0x33B5]); out+=l; assert a==0x33B9
    P(''); P('%s:\t; ch3 wave (instruments 2 and 4)'%wavn[0x33B9]); out+=db_lines(rom.bytes(0,0x33B9,16)); P('')
    P('WbInstTable:')
    it=[rom.w(0,0x33C9+2*i) for i in range(7)]
    P('\tdw '+', '.join('WbInst%d'%i for i in range(7)))
    a=0x33D7
    for i in range(7):
        assert it[i]==a
        s,n=inst_lines(rom,0,a,envn,wavn); P('WbInst%d:%s'%(i,s)); a+=n
    assert a==0x33FC
    P('')
    out+=code_lines2(rom,0,0x33FC,0x382D,L,R,CM,IMM)
    P(''); P('; 48 notes, C2-B5'); P('WbFreqTable:')
    fr=[rom.w(0,0x382D+2*i) for i in range(48)]
    for i in range(0,48,12): P('\tdw '+', '.join(hx(x,4) for x in fr[i:i+12]))
    P('')
    # songs
    songs=[(rom.w(0,0x388D+4*i),rom.w(0,0x388D+4*i+2)) for i in range(16)]
    tl={}
    def add(a,nm,cmt=''): tl.setdefault(a,[]).append((nm,'p',cmt))
    for i,(c2,c1) in enumerate(songs):
        add(c2,'WbSong%02d_Ch2'%i,'song 13 ch1 has no end marker and runs on into here' if i==14 else ''); add(c1,'WbSong%02d_Ch1'%i)
    P('; Song = (ch2 sequence, ch1 sequence). Song 15 lives in bank 3 and only plays')
    P('; correctly while bank 3 is mapped.')
    P('WbSongTable:')
    for i,(c2,c1) in enumerate(songs): P('\tdw WbSong%02d_Ch2, WbSong%02d_Ch1\t; %d'%(i,i,i))
    P('')
    P('; $38CD-$398D is game code and data (a graphics loader and its table), not sound.')
    P('')
    P('SECTION "Workboy music", ROM0[$398E]'); P('')
    P('; Sequences: note NOTE, frames / rest frames / snd_inst n (ignored by the driver)')
    P('; / snd_end (stops all music; the $01 after each $FF is never read).')
    out+=track_lines(rom,0,0x398E,0x3FAD,tl,1,None)
    P('; $3FAD-$3FFF is not sound data: leftover 16-bit x86 code from the PC tools.')
    P('')
    P('SECTION "Workboy music bank 3", ROMX[$461E], BANK[$03]'); P('')
    out+=track_lines(rom,3,0x461E,0x47A2,tl,1,None)
    open(outp,'w').write('\n'.join(out)+'\n')
    return [(0,0x0B76,0x0B99),(0,0x33B1,0x38CD),(0,0x398E,0x3FAD),(3,0x461E,0x47A2)]

